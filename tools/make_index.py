"""Builds the ReaPack index (index.xml), the action files (actions/) and the
release ZIP (dist/) for the version in the header of reawarp.lua.

Usage: python tools/make_index.py

Each release: raise "@version" (and "@changelog") in reawarp.lua, run this,
commit, tag "v<version>", push the tag and attach dist/reawarp-<version>.zip to
the GitHub release. The index links the files of that tag, and keeps the
earlier versions.

Copyright (C) 2026 Gabriel Schuck. GPL-3.0-or-later (see LICENSE).
"""
import datetime
import os
import re
import urllib.parse
import xml.etree.ElementTree as ET
import zipfile

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
REPO = 'https://github.com/gabrielschuck/reawarp'
CATEGORY = 'Tempo'
MAIN = 'reawarp.lua'
BACKEND = [('backend/reawarp_beat_this.py', None),
           ('backend/install_beat_this.bat', 'windows'),
           ('backend/install_beat_this.sh', 'darwin'),
           ('backend/install_beat_this.sh', 'linux')]


def header():
    src = open(os.path.join(ROOT, MAIN), encoding='utf-8').read()
    version = re.search(r'^-- @version (\S+)', src, re.M).group(1)
    author = re.search(r'^-- @author (.+)$', src, re.M).group(1).strip()
    desc = re.search(r'^-- @description (.+)$', src, re.M).group(1).strip()
    m = re.search(r'^-- @changelog\n((?:--   .*\n)+)', src, re.M)
    changelog = '\n'.join(l[5:] for l in m.group(1).splitlines()) if m else ''
    actions = re.findall(r'\{ "(\w+)", "(reawarp - [^"]+\.lua)" \}', src)
    return src, version, author, desc, changelog, actions


def stub(action):
    # the same text core.install_actions writes
    return ('-- Generated by reawarp.lua. Do not edit: all the code is in reawarp.lua.\n'
            f'REAWARP_ACTION = "{action}"\n'
            'dofile(debug.getinfo(1, "S").source:match("^@?(.*[\\\\/])") .. "../reawarp.lua")\n')


def main():
    src, version, author, desc, changelog, actions = header()
    os.makedirs(os.path.join(ROOT, 'actions'), exist_ok=True)
    for action, name in actions:
        with open(os.path.join(ROOT, 'actions', name), 'w', encoding='utf-8', newline='\n') as f:
            f.write(stub(action))

    path = os.path.join(ROOT, 'index.xml')
    if os.path.exists(path):
        index = ET.parse(path).getroot()
    else:
        index = ET.Element('index', version='1', name='reawarp')
        ET.SubElement(index, 'metadata')
        ET.SubElement(index.find('metadata'), 'link', rel='website').text = REPO
    cat = index.find(f"category[@name='{CATEGORY}']")
    if cat is None:
        cat = ET.SubElement(index, 'category', name=CATEGORY)
    pkg = cat.find(f"reapack[@name='{MAIN}']")
    if pkg is None:
        pkg = ET.SubElement(cat, 'reapack', name=MAIN, type='script', desc=desc)
        meta = ET.SubElement(pkg, 'metadata')
        ET.SubElement(meta, 'link', rel='website').text = REPO
    pkg.set('desc', desc)
    old = pkg.find(f"version[@name='{version}']")
    if old is not None:
        pkg.remove(old)
    ver = ET.SubElement(pkg, 'version', name=version, author=author,
                        time=datetime.datetime.now(datetime.timezone.utc).strftime('%Y-%m-%dT%H:%M:%SZ'))
    ET.SubElement(ver, 'changelog').text = changelog
    base = f'{REPO}/raw/v{version}/'

    def source(rel, **attrs):
        e = ET.SubElement(ver, 'source', **attrs)
        e.text = base + urllib.parse.quote(rel)
    source(MAIN, main='main')
    for _, name in actions:
        source('actions/' + name, file='actions/' + name, main='main')
    for rel, platform in BACKEND:
        source(rel, file=rel, **({'platform': platform} if platform else {}))
    ET.indent(index)
    ET.ElementTree(index).write(path, encoding='utf-8', xml_declaration=True)

    os.makedirs(os.path.join(ROOT, 'dist'), exist_ok=True)
    zpath = os.path.join(ROOT, 'dist', f'reawarp-{version}.zip')
    files = [MAIN, 'README.md', 'README.pt-BR.md', 'README.es.md', 'LICENSE'] + ['actions/' + n for _, n in actions] \
        + sorted({rel for rel, _ in BACKEND})
    with zipfile.ZipFile(zpath, 'w', zipfile.ZIP_DEFLATED) as z:
        for rel in files:
            z.write(os.path.join(ROOT, rel), 'reawarp/' + rel)
    print(f'version {version}: index.xml, {len(actions)} actions, {zpath}')


if __name__ == '__main__':
    main()
